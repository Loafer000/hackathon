const DICTS: Record<Lang, Dict> = { en, hi, mr, bn }

export const LANG_NAMES: Record<Lang, { native: string; en: string; short: string }> = {
  en: { native: 'English', en: 'English', short: 'EN' },
  hi: { native: 'हिन्दी', en: 'Hindi', short: 'हि' },
  mr: { native: 'मराठी', en: 'Marathi', short: 'म' },
  bn: { native: 'বাংলা', en: 'Bengali', short: 'বা' },
}

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const s = DICTS[lang][key] ?? en[key] ?? key
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''))
}

export type TFn = (key: Key, vars?: Record<string, string | number>) => string

export function useT() {
  const { session } = useApp()
  const lang = session.lang
  const t: TFn = (key, vars) => translate(lang, key, vars)
  const L = (o: Record<Lang, string>) => o[lang] ?? o.en
  return { t, L, lang }
}
